export type MoodId =
  | 'funny' | 'romantic' | 'thrilling' | 'mindblowing' | 'emotional'
  | 'adventurous' | 'relaxed' | 'scary' | 'curious' | 'surprise'

export type Company = 'solo' | 'partner' | 'friends' | 'family' | 'group'
export type AgeGroup = 'children' | 'teens' | 'adults' | 'mixed'
export type RuntimeChoice = 'any' | 'short' | 'medium' | 'long'
export type ReleasePeriod = 'any' | 'recent' | '2010s' | '2000s' | 'classic'
export type Certification = 'G' | 'PG' | 'PG-13' | 'R' | 'NC-17'

/** Canonical genre names (identical to TMDB's English genre names). */
export type Genre = string

export interface Movie {
  id: number
  title: string
  year?: number
  genres: Genre[]
  /** Minutes. Only present when the data source provided it. */
  runtime?: number
  /** US certification (G, PG, PG-13, R, NC-17). Undefined when unknown/unrated. */
  certification?: Certification
  overview: string
  tagline?: string
  posterUrl?: string
  backdropUrl?: string
  /** ISO 639-1 code of the original language. */
  originalLanguage: string
  voteAverage?: number
  voteCount?: number
  /** Theme keywords (TMDB keywords when loaded). */
  keywords: string[]
  adult?: boolean
  source: 'tmdb' | 'demo'
  /** True once runtime/certification/keywords were fetched. */
  detailsLoaded: boolean
}

export interface Preferences {
  mood: MoodId | null
  secondaryMood: MoodId | null
  company: Company | null
  ageGroup: AgeGroup | null
  genres: Genre[]
  runtime: RuntimeChoice
  /** 'any' or an ISO 639-1 original-language code. */
  language: string
  maxRating: 'any' | Certification
  releasePeriod: ReleasePeriod
  excludeWatched: boolean
}

export interface Reason {
  /** verified = comes straight from the data source; inferred = computed by the app. */
  kind: 'verified' | 'inferred'
  text: string
}

export interface ScoreComponent {
  key: string
  label: string
  /** 0..1 */
  value: number
  weight: number
}

export interface Recommendation {
  movie: Movie
  /** 0..1 estimated match score generated by the app. */
  score: number
  components: ScoreComponent[]
  summary: string
  reasons: Reason[]
}

export interface Settings {
  theme: 'dark' | 'light' | 'system'
  /** Language for TMDB titles and synopses (BCP 47). */
  metadataLanguage: string
  /** Force the built-in demo catalogue even when TMDB is configured. */
  forceDemo: boolean
}

export type DataMode = 'tmdb' | 'demo'
