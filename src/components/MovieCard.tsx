import { href } from '../hooks/useRoute'
import { useStore } from '../hooks/useStore'
import type { Movie } from '../types'
import { formatRuntime } from '../utils/format'
import { Icon } from './Icon'
import { Poster } from './Poster'
import { Badge } from './ui'

export function FavoriteButton({ movie, label = false }: { movie: Movie; label?: boolean }) {
  const { favorites, toggleFavorite } = useStore()
  const on = Boolean(favorites[movie.id])
  return (
    <button type="button" className={`iconbtn ${on ? 'is-on' : ''} ${label ? 'iconbtn--label' : ''}`} aria-pressed={on}
      aria-label={on ? `Remove ${movie.title} from favorites` : `Add ${movie.title} to favorites`}
      onClick={(e) => { e.preventDefault(); e.stopPropagation(); toggleFavorite(movie) }}>
      <Icon name="heart" size={20} filled={on} />
      {label && <span>{on ? 'Saved' : 'Favorite'}</span>}
    </button>
  )
}

export function MetaLine({ movie }: { movie: Movie }) {
  const parts = [movie.year, formatRuntime(movie.runtime)].filter(Boolean)
  return (
    <p className="meta">
      {parts.join(' · ')}
      {movie.certification ? <Badge tone="neutral" title="Official US rating">{movie.certification}</Badge> : null}
    </p>
  )
}

/** Compact poster card used in grids, rails and favorites. */
export function MovieCard({ movie, score, children }: { movie: Movie; score?: number; children?: React.ReactNode }) {
  return (
    <article className="card">
      <a href={href.movie(movie.id)} className="card__link" aria-label={`${movie.title}, details`}>
        <div className="card__poster">
          <Poster movie={movie} />
          {score !== undefined && <span className="card__score" title="Estimated match score generated by the app">{Math.round(score * 100)}%</span>}
        </div>
        <div className="card__body">
          <h3 className="card__title">{movie.title}</h3>
          <MetaLine movie={movie} />
          {movie.genres.length > 0 && <p className="card__genres">{movie.genres.slice(0, 3).join(' · ')}</p>}
        </div>
      </a>
      <div className="card__fav"><FavoriteButton movie={movie} /></div>
      {children}
    </article>
  )
}
