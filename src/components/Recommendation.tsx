import { href, navigate } from '../hooks/useRoute'
import { useStore } from '../hooks/useStore'
import type { Recommendation } from '../types'
import { Backdrop, Poster } from './Poster'
import { FavoriteButton, MetaLine } from './MovieCard'
import { Badge, Button } from './ui'
import { Icon } from './Icon'

export function ReasonList({ rec }: { rec: Recommendation }) {
  return (
    <ul className="reasons">
      {rec.reasons.map((r, i) => (
        <li key={i}>
          <Badge tone={r.kind === 'verified' ? 'success' : 'purple'}
            title={r.kind === 'verified' ? 'Comes directly from the movie data source' : 'Inferred by VibeFlix from genres and synopsis'}>
            {r.kind === 'verified' ? 'Data' : 'Inferred'}
          </Badge>
          <span>{r.text}</span>
        </li>
      ))}
    </ul>
  )
}

export function MatchScore({ score }: { score: number }) {
  return (
    <span className="matchscore" title="Estimated match score generated by VibeFlix – not a scientific prediction">
      <span className="matchscore__n">{Math.round(score * 100)}%</span>
      <span className="matchscore__l">estimated match</span>
    </span>
  )
}

export function WatchedButton({ rec, size = 'md' }: { rec: Pick<Recommendation, 'movie'>; size?: 'sm' | 'md' }) {
  const { watched, toggleWatched } = useStore()
  const on = Boolean(watched[rec.movie.id])
  return (
    <Button size={size} variant="secondary" icon={on ? 'check' : 'eye'} aria-pressed={on} onClick={() => toggleWatched(rec.movie)}>
      {on ? 'Watched' : 'Already watched'}
    </Button>
  )
}

export function BestMatch({ rec, onAnother, onNewSearch }: { rec: Recommendation; onAnother: () => void; onNewSearch: () => void }) {
  const { movie } = rec
  return (
    <section className="best" aria-labelledby="best-title">
      <div className="best__backdrop" aria-hidden="true"><Backdrop movie={movie} /></div>
      <div className="best__inner">
        <a href={href.movie(movie.id)} className="best__poster" aria-label={`${movie.title}, details`}><Poster movie={movie} eager /></a>
        <div className="best__info">
          <Badge tone="accent">★ Best match</Badge>
          <h2 id="best-title" className="best__title">{movie.title}</h2>
          <MetaLine movie={movie} />
          <p className="best__genres">{movie.genres.join(' · ')}</p>
          <MatchScore score={rec.score} />
          <p className="best__overview">{movie.overview || 'No synopsis available.'}</p>
          <p className="best__why"><Icon name="sparkle" size={16} /> {rec.summary}</p>
          <ReasonList rec={rec} />
          <div className="actions">
            <Button variant="primary" onClick={() => navigate(href.movie(movie.id))}>View details</Button>
            <FavoriteButton movie={movie} label />
            <WatchedButton rec={rec} />
            <Button icon="refresh" onClick={onAnother}>Show me another movie</Button>
            <Button variant="ghost" onClick={onNewSearch}>Start a new search</Button>
          </div>
        </div>
      </div>
    </section>
  )
}

export function ResultCard({ rec, onAnother }: { rec: Recommendation; onAnother: () => void }) {
  const { movie } = rec
  return (
    <article className="result">
      <a href={href.movie(movie.id)} className="result__poster" aria-label={`${movie.title}, details`}>
        <Poster movie={movie} />
      </a>
      <div className="result__body">
        <div className="result__head">
          <h3 className="result__title"><a href={href.movie(movie.id)}>{movie.title}</a></h3>
          <MatchScore score={rec.score} />
        </div>
        <MetaLine movie={movie} />
        <p className="card__genres">{movie.genres.slice(0, 3).join(' · ')}</p>
        <p className="result__overview">{movie.overview || 'No synopsis available.'}</p>
        <p className="result__why"><Icon name="sparkle" size={14} /> {rec.summary}</p>
        <div className="actions actions--tight">
          <FavoriteButton movie={movie} />
          <WatchedButton rec={rec} size="sm" />
          <Button size="sm" icon="refresh" onClick={onAnother}>Show another</Button>
        </div>
      </div>
    </article>
  )
}
